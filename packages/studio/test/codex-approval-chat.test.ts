import test from 'node:test';
import assert from 'node:assert/strict';
import { EventEmitter } from 'node:events';
import { PassThrough } from 'node:stream';
import { CliChatManager } from '../server/CliChat.js';

const wait = async (condition: () => boolean) => { for (let i=0;i<200&&!condition();i++) await new Promise(r=>setTimeout(r,5)); assert.ok(condition()); };
test('Codex app-server asks and receives allow or deny without changing the sandbox', async () => {
  const proc:any=new EventEmitter(); proc.stdin=new PassThrough();proc.stdout=new PassThrough();proc.stderr=new PassThrough();proc.kill=()=>true;
  let input='';proc.stdin.on('data',(c:Buffer)=>input+=c.toString());
  const calls=()=>input.split('\n').filter(Boolean).map(line=>JSON.parse(line));
  const say=(x:unknown)=>proc.stdout.write(JSON.stringify(x)+'\n');
  const chats=new CliChatManager((()=>proc) as any,undefined,((_id:string,args:string[])=>{assert.deepEqual(args,['app-server']);return {command:'codex',args}}) as any);
  chats.send('room',{agent:'codex',cwd:process.cwd(),text:'test',permission:'ask'});
  assert.equal(calls()[0].method,'initialize');say({id:1,result:{}});
  assert.equal(calls().find(m=>m.id===2).params.approvalPolicy,'untrusted');
  assert.equal(calls().find(m=>m.id===2).params.sandbox,'workspace-write');
  say({id:2,result:{thread:{id:'thread-1'}}});assert.equal(calls().find(m=>m.id===3).params.input[0].text.split('\n\n[วิธีถามผู้ใช้]')[0],'test');
  say({id:99,method:'item/commandExecution/requestApproval',params:{command:'echo test'}});
  await wait(()=>chats.snapshot('room').items.some(i=>i.kind==='permission'));
  const card=chats.snapshot('room').items.find(i=>i.kind==='permission')!;
  assert.equal(card.kind,'permission');if(card.kind!=='permission')return;
  assert.equal(card.detail,'echo test'); assert.equal(chats.answerPermission('room',card.requestId,'allow'),true);
  assert.deepEqual(calls().find(m=>m.id===99),{id:99,result:{decision:'accept'}});
  say({id:100,method:'item/fileChange/requestApproval',params:{reason:'write'}});
  await wait(()=>chats.snapshot('room').items.filter(i=>i.kind==='permission').length===2);
  const second=chats.snapshot('room').items.filter(i=>i.kind==='permission')[1];if(second.kind!=='permission')return;
  assert.equal(chats.answerPermission('room',second.requestId,'deny'),true);
  assert.deepEqual(calls().find(m=>m.id===100),{id:100,result:{decision:'decline'}});
  say({id:101,method:'item/commandExecution/requestApproval',params:{command:'echo cancelled'}});
  const third=chats.snapshot('room').items.filter(i=>i.kind==='permission')[2];if(third.kind!=='permission')return;
  assert.equal(chats.answerPermission('room',third.requestId,'always'),false, 'do not promise persistence across server restarts');
  say({method:'serverRequest/resolved',params:{requestId:101,threadId:'thread-1'}});
  assert.equal(chats.answerPermission('room',third.requestId,'allow'),false);
  assert.equal((chats.snapshot('room').items.find(i=>i.id===third.id) as any).status,'expired');
  say({id:102,method:'item/tool/requestUserInput',params:{}});
  assert.equal(calls().find(m=>m.id===102).error.code,-32601, 'unsupported requests are never approved');
  say({method:'thread/tokenUsage/updated',params:{threadId:'thread-1',tokenUsage:{total:{inputTokens:100,cachedInputTokens:70,outputTokens:12}}}});
  say({method:'turn/completed',params:{turn:{status:'completed'}}});proc.emit('close',0);
  assert.equal(chats.isRunning('room'),false);
  assert.ok(chats.snapshot('room').items.some(item=>item.kind==='notice' && /input สะสมในบทสนทนา 100/.test(item.text)));
});

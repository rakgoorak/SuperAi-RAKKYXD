import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import http from 'node:http';
import path from 'node:path';

const root = path.resolve('packages/studio/client/dist');
const output = path.resolve('output/conversation-interactions');
await fs.mkdir(output, { recursive: true });
const server = http.createServer(async (req, res) => {
  try {
    const pathname = new URL(req.url, 'http://localhost').pathname;
    const file = path.resolve(root, pathname === '/' ? 'index.html' : `.${decodeURIComponent(pathname)}`);
    if (!file.startsWith(root + path.sep)) return res.writeHead(403).end();
    const content = await fs.readFile(file);
    res.writeHead(200, { 'Content-Type': ({ '.js': 'text/javascript', '.css': 'text/css', '.html': 'text/html', '.woff2': 'font/woff2' })[path.extname(file)] || 'application/octet-stream' }).end(content);
  } catch { res.writeHead(404).end(); }
});
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const browser = await chromium.launch({ channel: 'chrome', headless: true });
let checks = 0;
const check = (value, message) => { assert.ok(value, message); checks++; console.log(`PASS ${message}`); };
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, reducedMotion: 'reduce' });
  page.setDefaultTimeout(12000);
  const errors = [], sends = [], forks = [], sockets = new Map();
  page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(() => {
    localStorage.setItem('superai-setup-dismissed', '1'); localStorage.setItem('superai-mode', 'code');
    localStorage.setItem('superai-canvas-layout-v2', 'tabs'); localStorage.setItem('superai-preview', 'false');
    window.copies = [];
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async value => {
      if (window.failCopy) throw new Error('blocked'); window.copies.push(value);
    } } });
  });
  const workspace = { id: 'interactions', name: 'Conversation', rootPath: output, threads: [] };
  const sessions = ['One', 'Two'].map((name, index) => ({ id: `ui-${index}`, name, wsId: workspace.id, agentType: 'codex', cwd: output, status: 'exited', dormant: true, view: 'chat', createdAt: 1 }));
  const answer = '# ผลทดสอบ\n\n**test** test พร้อมใช้งาน\n\n```bash\nnpm test\n```\n\nข้อความที่ไม่ตรงคำค้น';
  const items = [{ id: 'u1', kind: 'user', text: 'ขอ test หน้า', at: 1 }, { id: 'a1', kind: 'assistant', text: answer, at: 2 }, { id: 'tool1', kind: 'tool', tool: 'command', title: 'echo sample', output: 'hiddenneedle', status: 'done', at: 3 }];
  await page.routeWebSocket('**/ws/chat/**', socket => {
    const id = socket.url().split('/').at(-1); sockets.set(id, socket);
    socket.send(JSON.stringify({ type: 'snapshot', chat: { items, running: false } }));
  });
  await page.route('**/api/**', async route => {
    const pathname = new URL(route.request().url()).pathname;
    let json = [];
    if (pathname === '/api/workspaces') json = [workspace];
    else if (pathname === '/api/terminals' || pathname === '/api/sessions') json = sessions;
    else if (pathname === '/api/clis') json = [{ id: 'codex', name: 'Codex', command: 'codex', available: true, nodeReady: true, maxSessions: 10 }];
    else if (pathname.endsWith('/chat/settings')) json = { agent: 'codex', model: 'model-a', effort: 'high', skills: [] };
    else if (pathname.includes('/auth')) json = { id: 'codex', status: 'authenticated', note: 'ready', checkedAt: Date.now() };
    else if (pathname.includes('/models')) json = { models: ['model-a'], efforts: ['high'] };
    else if (pathname.endsWith('/context')) json = { cwd: output, isGit: false, branch: null, branches: [] };
    else if (pathname.endsWith('/files') || pathname.endsWith('/pinned-content')) json = { files: [] };
    else if (pathname.endsWith('/chat/fork')) {
      const body = route.request().postDataJSON(); forks.push(body);
      json = { ...sessions[0], id: `fork-${forks.length}`, name: body.selection ? 'Side' : 'Fork', createdAt: Date.now() };
      sessions.push(json);
    } else if (pathname.endsWith('/chat')) {
      if (route.request().method() === 'POST') { sends.push(route.request().postDataJSON()); json = { success: true }; }
      else json = { items, running: false };
    }
    return route.fulfill({ json });
  });
  await page.goto(`http://127.0.0.1:${server.address().port}`, { waitUntil: 'networkidle' });
  await page.getByLabel('เป้าหมายคำสั่ง', { exact: true }).selectOption('active');
  await page.locator('.session-tab').filter({ hasText: 'One' }).locator('button').first().click();
  const pane = page.locator('[data-session-id="ui-0"]');
  const body = pane.locator('[data-message-body="a1"]');
  const composer = page.getByLabel('คำสั่ง', { exact: true });
  await body.waitFor();
  await composer.fill('existing draft');
  await page.keyboard.press('Control+f');
  const finder = pane.getByRole('search');
  const query = finder.getByLabel('คำค้นหาในบทสนทนา');
  await query.fill('TEST');
  await finder.getByRole('status').filter({ hasText: '1/4' }).waitFor();
  check(await body.isVisible() && await body.innerText().then(text => text.includes('ข้อความที่ไม่ตรงคำค้น')), 'search preserves unmatched messages and paragraph context');
  check(await page.evaluate(() => Array.from(CSS.highlights.keys()).some(key => key.startsWith('matches-'))), 'search registers native range highlights');
  await query.press('Enter');
  check(await finder.getByRole('status').innerText() === '2/4', 'Enter advances to the next occurrence');
  await query.press('Shift+Enter');
  check(await finder.getByRole('status').innerText() === '1/4', 'Shift+Enter returns to the previous occurrence');
  await finder.getByRole('button', { name: 'ผลก่อนหน้า', exact: true }).click();
  check(await finder.getByRole('status').innerText() === '4/4', 'previous result wraps to the last occurrence');
  await query.fill('test test');
  await finder.getByRole('status').filter({ hasText: '1/1' }).waitFor();
  check(true, 'search spans Markdown inline formatting boundaries');
  await query.fill('hiddenneedle');
  await pane.locator('.chat-tools-summary').click();
  await pane.locator('.chat-tool-row').click();
  await finder.getByRole('status').filter({ hasText: '1/1' }).waitFor();
  check(true, 'expanding tool output refreshes search against newly visible text');
  await pane.locator('.chat-tools-summary').click();
  await finder.getByRole('status').filter({ hasText: '0/0' }).waitFor();
  check(true, 'collapsing output removes inaccessible matches');
  await query.fill('test');
  sockets.get('ui-0').send(JSON.stringify({ type: 'item', item: { ...items[1], text: answer + '\n\nnew test' } }));
  await finder.getByRole('status').filter({ hasText: '/5' }).waitFor();
  check(true, 'streamed text refreshes occurrence counts');
  await query.fill('ไม่มีคำนี้');
  await finder.getByRole('status').filter({ hasText: '0/0' }).waitFor();
  check(await finder.getByRole('button', { name: 'ผลถัดไป', exact: true }).isDisabled(), 'no matches shows zero and disables navigation');
  await query.fill('test');
  await page.screenshot({ path: path.join(output, 'search-desktop.png') });
  await query.press('Escape');
  check(await finder.count() === 0 && await composer.inputValue() === 'existing draft', 'Escape closes search without changing the draft');
  check(await page.evaluate(() => CSS.highlights.size) === 0, 'closing finder removes all stale highlights');

  const selectParagraph = async () => { await body.locator('p').first().selectText(); await page.getByRole('toolbar', { name: 'จัดการข้อความที่เลือก' }).waitFor(); };
  const rightClickSelection = async () => {
    const rect = await page.evaluate(() => { const rect = getSelection().getRangeAt(0).getBoundingClientRect(); return { x: rect.x + 4, y: rect.y + 4 }; });
    await page.mouse.click(rect.x, rect.y, { button: 'right' });
    await page.getByRole('menu', { name: 'ตัวเลือกข้อความ' }).waitFor();
  };
  await selectParagraph();
  check(await page.getByRole('button', { name: 'Start a side chat', exact: true }).isVisible(), 'selecting text displays the side chat and Reply toolbar');
  await page.screenshot({ path: path.join(output, 'selection-desktop.png') });
  await page.getByRole('button', { name: 'Reply', exact: true }).click();
  check((await composer.inputValue()).startsWith('existing draft') && (await composer.inputValue()).includes('> test test พร้อมใช้งาน'), 'Reply appends the selected quote and preserves the existing draft');
  check(sends.length === 0, 'Reply prepares a draft without sending');
  await selectParagraph(); await rightClickSelection();
  const menu = page.getByRole('menu', { name: 'ตัวเลือกข้อความ' });
  await menu.getByRole('menuitem', { name: 'Copy Ctrl+C', exact: true }).click();
  check(await page.evaluate(() => window.copies.at(-1)) === 'test test พร้อมใช้งาน', 'Copy copies only the selected text');
  await body.locator('h4').click({ button: 'right' });
  await menu.getByRole('menuitem', { name: 'Copy message as Markdown', exact: true }).click();
  check(await page.evaluate(() => window.copies.at(-1)) === answer + '\n\nnew test', 'Copy Markdown preserves the exact source');
  await body.locator('h4').click({ button: 'right' });
  await menu.getByRole('menuitem', { name: 'Copy message', exact: true }).click();
  const plain = await page.evaluate(() => window.copies.at(-1));
  check(plain.includes('test test พร้อมใช้งาน') && !plain.includes('**') && !plain.includes('คัดลอก') && !plain.includes('BASH'), 'Copy message excludes Markdown markers and code toolbar labels: ' + JSON.stringify(plain));
  await page.evaluate(() => getSelection().removeAllRanges());
  await body.locator('pre code').click({ button: 'right' });
  await menu.getByRole('menuitem', { name: 'Copy code', exact: true }).click();
  check(await page.evaluate(() => window.copies.at(-1)) === 'npm test', 'code context menu copies only the code block');
  await page.evaluate(() => { window.failCopy = true; });
  await body.locator('h4').click({ button: 'right' });
  await menu.getByRole('menuitem', { name: 'Copy message', exact: true }).click();
  await pane.getByRole('alert').filter({ hasText: 'คัดลอกไม่ได้' }).waitFor();
  check(true, 'clipboard failures remain visible and recoverable');
  await page.evaluate(() => { window.failCopy = false; });
  await page.keyboard.press('Escape');
  await selectParagraph(); await rightClickSelection();
  await menu.getByRole('menuitem', { name: 'Attach selection as context', exact: true }).click();
  await page.getByLabel('ข้อความที่แนบเป็นบริบท').getByText('test test พร้อมใช้งาน', { exact: true }).waitFor();
  check(sends.length === 0, 'attaching a selection adds a reviewable context chip without sending');
  await page.reload({ waitUntil: 'networkidle' });
  await page.getByLabel('ข้อความที่แนบเป็นบริบท').getByText('test test พร้อมใช้งาน', { exact: true }).waitFor();
  check(true, 'attached message context persists across reload');
  await page.getByRole('button', { name: 'เอาข้อความอ้างอิงออก', exact: true }).click();
  check(await page.locator('.message-context-chip').count() === 0, 'attached context can be removed before sending');
  await selectParagraph();
  await page.keyboard.press('Control+Shift+l');
  await page.locator('.message-context-chip').waitFor();
  check(sends.length === 0, 'Ctrl+Shift+L attaches the selection without sending');
  await composer.fill('explain this');
  await page.getByRole('button', { name: 'ส่งคำสั่ง (Enter)', exact: true }).click();
  await page.waitForFunction(() => !document.querySelector('.message-context-chip'));
  check(sends.length === 1 && sends[0].text.includes('test test พร้อมใช้งาน') && sends[0].text.includes('explain this'), 'sending includes attached context and clears the chip after success');

  await body.locator('h4').click({ button: 'right' });
  await menu.getByRole('menuitem', { name: 'Pin as chapter', exact: true }).click();
  await pane.getByRole('button', { name: 'หมุดบทสนทนา', exact: true }).click();
  check(await pane.getByLabel('รายการหมุด').isVisible(), 'pinned messages appear as chapter jump links');
  await page.reload({ waitUntil: 'networkidle' });
  await pane.getByRole('button', { name: 'หมุดบทสนทนา', exact: true }).waitFor();
  check(true, 'chapters persist across reload');
  await pane.getByRole('button', { name: 'หมุดบทสนทนา', exact: true }).click();
  await pane.getByRole('button', { name: 'เอาหมุดออก', exact: true }).click();
  check(await pane.getByRole('button', { name: 'หมุดบทสนทนา', exact: true }).count() === 0, 'chapters can be removed');
  await selectParagraph(); await rightClickSelection();
  await page.setViewportSize({ width: 760, height: 650 });
  await body.locator('h4').click({ button: 'right' });
  const bounds = await menu.boundingBox();
  check(bounds.x >= 0 && bounds.y >= 0 && bounds.x + bounds.width <= 760 && bounds.y + bounds.height <= 650, 'context menu stays inside a small viewport');
  check(await menu.getByRole('menuitem').evaluateAll(buttons => buttons.every(button => {
    const rect = button.getBoundingClientRect();
    return button.contains(document.elementFromPoint(rect.x + rect.width / 2, rect.y + rect.height / 2));
  })), 'all menu actions remain above composer and pane overlays');
  await page.screenshot({ path: path.join(output, 'context-menu-narrow.png') });
  await page.keyboard.press('End');
  check(await menu.getByRole('menuitem').last().evaluate(element => element === document.activeElement), 'keyboard End focuses the last menu action');
  await page.keyboard.press('Escape');
  check(await menu.count() === 0, 'Escape closes the context menu');
  await page.setViewportSize({ width: 1440, height: 900 });
  await body.locator('h4').click({ button: 'right' });
  await menu.getByRole('menuitem', { name: /Fork from here/ }).click();
  await page.locator('[data-session-id="fork-1"].focused').waitFor();
  check(forks.length === 1 && forks[0].messageId === 'a1' && !forks[0].selection && sends.length === 1, 'Fork creates and selects a separate session without sending a prompt');
  await page.locator('.session-tab').filter({ hasText: 'One' }).locator('button').first().click();
  await selectParagraph();
  await page.getByRole('button', { name: 'Start a side chat', exact: true }).click();
  await page.locator('[data-session-id="fork-2"].focused').waitFor();
  check(forks.length === 2 && forks[1].selection === 'test test พร้อมใช้งาน', 'side chat carries only the selected excerpt to the server');
  check(await pane.isVisible() && await page.locator('[data-session-id="fork-2"]').isVisible(), 'side chat opens alongside the original conversation');
  await page.keyboard.press('Control+f');
  check(await page.getByRole('search', { name: 'ค้นหาในบทสนทนานี้' }).count() === 1, 'only the focused pane handles Ctrl+F in split view');
  check(errors.length === 0, `no renderer exceptions: ${errors.join('; ')}`);
  await fs.writeFile(path.join(output, 'results.json'), JSON.stringify({ checks, errors }, null, 2));
  console.log(JSON.stringify({ checks, output }));
} finally { await browser.close(); await new Promise(resolve => server.close(resolve)); }

import { _electron as electron } from 'playwright-core';
import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';

const require = createRequire(import.meta.url);
const output = path.resolve('output/playwright');
await fs.mkdir(output, { recursive: true });
const data = await fs.mkdtemp(path.join(output, 'accounts-'));
const app = await electron.launch({ executablePath: require('electron'), args: ['packages/desktop'], env: { SUPERAI_LANG: 'th', ...process.env, SUPERAI_DATA_DIR: data, SUPERAI_TEST_MODE: '1' }, timeout: 60000 });
try {
  const page = await app.firstWindow();
  page.setDefaultTimeout(15000);
  console.log("accounts smoke: window ready");
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/api/clis/*/auth*', route => route.fulfill({ json: { status: 'login-required', note: 'ยังไม่ได้เข้าสู่ระบบ', checkedAt: Date.now(), loginCommand: 'test' } }));
  await page.route('**/api/providers/*/models*', route => route.fulfill({ json: { models: ['test-model'], efforts: ['low', 'high'] } }));
  await page.route('**/api/opencode/models*', route => route.fulfill({ json: { models: ['opencode/test-free'] } }));
  await page.waitForSelector('.app-shell');
  console.log('accounts smoke: shell ready');
  await page.evaluate(() => localStorage.setItem('superai-setup-dismissed', '1'));
  await page.reload(); await page.waitForSelector('.app-shell');
  const request = (route, body, method) => page.evaluate(async ({ route, body, method }) => {
    const res = await fetch(route, { method: method || (body ? 'POST' : 'GET'), headers: { 'Content-Type': 'application/json' }, body: body ? JSON.stringify(body) : undefined });
    const value = await res.json(); if (!res.ok) throw Error(JSON.stringify(value)); return value;
  }, { route, body, method });
  const ws = await request('/api/workspaces', { name: 'ทดสอบหลายบัญชี', rootPath: data });
  await page.getByRole('button', { name: 'ทดสอบหลายบัญชี', exact: true }).click();
  await page.getByRole('button', { name: 'การตั้งค่า', exact: true }).click();
  await page.getByRole('button', { name: 'บัญชี AI', exact: true }).click();
  await page.locator('.accounts-panel').waitFor();
  await page.screenshot({ path: path.join(output, 'accounts-before.png') });
  const codex = page.locator('.account-provider').filter({ has: page.getByRole('heading', { name: 'ChatGPT (Codex)', exact: true }) });
  await codex.getByRole('textbox', { name: 'ชื่อบัญชีใหม่ ChatGPT (Codex)', exact: true }).fill('บัญชีงาน');
  await codex.getByRole('button', { name: 'เพิ่มบัญชี', exact: true }).click();
  await codex.getByText('บัญชีงาน', { exact: true }).waitFor();
  const card = codex.locator('.account-card').filter({ has: page.getByText('บัญชีงาน', { exact: true }) });
  await card.getByRole('button', { name: 'ใช้เป็นบัญชีเริ่มต้น', exact: true }).click();
  await card.getByText('เริ่มต้นสำหรับงานใหม่', { exact: true }).waitFor();
  const group = (await request('/api/accounts')).find(p => p.provider === 'codex');
  const a = group.profiles.find(p => p.name === 'บัญชีงาน');
  assert.ok(a.isDefault);
  const session = await request('/api/terminals/spawn', { agentType: 'codex', wsId: ws.id, name: 'ห้องบัญชีงาน' });
  assert.equal(session.accountId, a.id);
  await card.getByRole('button', { name: 'เปลี่ยนชื่อ', exact: true }).click();
  await card.getByRole('textbox', { name: 'ชื่อบัญชีใหม่', exact: true }).fill('ทีมพัฒนา');
  await card.getByRole('button', { name: 'บันทึกชื่อ', exact: true }).click();
  await codex.getByText('ทีมพัฒนา', { exact: true }).waitFor();
  await codex.getByRole('textbox', { name: 'ชื่อบัญชีใหม่ ChatGPT (Codex)', exact: true }).fill('บัญชีส่วนตัว');
  await codex.getByRole('button', { name: 'เพิ่มบัญชี', exact: true }).click();
  const personal = codex.locator('.account-card').filter({ has: page.getByText('บัญชีส่วนตัว', { exact: true }) });
  await personal.getByRole('button', { name: 'ใช้เป็นบัญชีเริ่มต้น', exact: true }).click();
  await personal.getByText('เริ่มต้นสำหรับงานใหม่', { exact: true }).waitFor();
  assert.equal((await request('/api/terminals')).find(s => s.id === session.id).accountId, a.id);
  const settings = await request(`/api/terminals/${session.id}/chat/settings`);
  assert.equal(settings.accountName, 'ทีมพัฒนา');
  assert.equal(settings.accountId, a.id);
  assert.equal(settings.agent, 'codex');
  await personal.getByRole('button', { name: 'นำออก', exact: true }).click();
  await personal.getByRole('button', { name: 'ยืนยันนำออก', exact: true }).click();
  await personal.waitFor({ state: 'detached' });
  assert.equal((await request('/api/accounts')).find(p => p.provider === 'codex').profiles.find(p => p.isDefault).id, 'system');
  const agy = page.locator('.account-provider').filter({ has: page.getByRole('heading', { name: 'Antigravity', exact: true }) });
  assert.equal(await agy.getByRole('button', { name: 'เพิ่มบัญชี', exact: true }).count(), 0);
  await page.screenshot({ path: path.join(output, 'accounts-desktop.png') });
  const overflow = await page.locator('.accounts-panel').evaluate(el => el.scrollWidth > el.clientWidth + 1);
  assert.equal(overflow, false);
  await app.evaluate(({ BrowserWindow }) => { const w = BrowserWindow.getAllWindows()[0]; w.unmaximize(); w.setContentSize(900, 700); });
  await page.screenshot({ path: path.join(output, 'accounts-compact.png') });
  assert.equal(await page.locator('.accounts-panel').evaluate(el => el.scrollWidth > el.clientWidth + 1), false);
  await page.getByRole('button', { name: 'Model และ Effort', exact: true }).click();
  assert.equal(await page.locator('.provider-defaults .account-picker').count(), 0);
  await page.getByRole('button', { name: 'เสร็จแล้ว', exact: true }).click();
  await page.getByRole('button', { name: 'สร้าง session', exact: true }).click();
  await page.locator('.cli-option').filter({ hasText: 'Codex' }).click();
  const picker = page.locator('.session-model .account-picker select');
  await picker.selectOption(a.id);
  assert.equal(await picker.inputValue(), a.id);
  await page.screenshot({ path: path.join(output, 'accounts-session-picker.png') });
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ passed: true, checks: ['create', 'default', 'rename', 'remove', 'tab binding', 'account settings', 'agy restriction', 'desktop and compact layout', 'session picker', 'model defaults'], data }));
} catch (error) { console.error(error); throw error; } finally {
  const timer = setTimeout(() => app.process().kill(), 10000);
  try { await app.close(); } finally { clearTimeout(timer); }
}

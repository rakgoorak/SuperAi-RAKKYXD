// Merge the tr() source strings in use into the dictionaries (window and server) without losing
// edited wording. Strings no longer used are dropped.
// Run with --check to report missing translations without writing files.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { sources } from './i18n-text.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const ts = require('typescript');
const locales = ['en', 'ja', 'zh'];
const AREAS = { client: 'packages/studio/client/src/locales', server: 'packages/studio/server/locales' };
const checkOnly = process.argv.includes('--check');

function readTranslations(file) {
  const source = fs.readFileSync(file, 'utf8');
  const ast = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  let initializer;
  function visit(node) {
    if (ts.isVariableDeclaration(node) && node.name.getText(ast) === 'text') initializer = node.initializer;
    ts.forEachChild(node, visit);
  }
  visit(ast);
  if (!initializer || !ts.isObjectLiteralExpression(initializer)) {
    throw new Error(`${path.relative(root, file)} must export a text object`);
  }
  const result = {};
  for (const item of initializer.properties) {
    if (!ts.isPropertyAssignment(item) || !ts.isStringLiteralLike(item.initializer)) continue;
    const key = ts.isStringLiteralLike(item.name) || ts.isIdentifier(item.name) ? item.name.text : null;
    if (key !== null) result[key] = item.initializer.text;
  }
  return result;
}

let incomplete = false;
for (const [area, dir] of Object.entries(AREAS)) for (const locale of locales) {
  const sourceKeys = [...sources(area).keys()];
  const file = path.join(root, dir, `${locale}.ts`);
  const current = readTranslations(file);
  const merged = Object.fromEntries(sourceKeys.map((key) => [key, current[key] || '']));
  const missing = sourceKeys.filter((key) => !merged[key]?.trim());
  if (missing.length) incomplete = true;
  if (checkOnly) {
    console.log(`${area} ${locale}: ${sourceKeys.length - missing.length}/${sourceKeys.length} translated`);
    if (missing.length) console.log(`  Missing: ${missing.slice(0, 20).join(' | ')}`);
    continue;
  }
  fs.writeFileSync(
    file,
    `// Generated by scripts/i18n-merge.mjs. Keep translations keyed by Thai source text.\nconst text: Record<string, string> = ${JSON.stringify(merged, null, 2)};\nexport default text;\n`,
    'utf8',
  );
  console.log(`${area} ${locale}: merged ${sourceKeys.length} source strings${missing.length ? `; ${missing.length} need translation` : ''}`);
}

if (checkOnly && incomplete) process.exitCode = 1;

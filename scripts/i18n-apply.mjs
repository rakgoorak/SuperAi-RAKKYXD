// Apply a reviewed translation table over a dictionary directory.
//   node scripts/i18n-apply.mjs <locales dir> <keys.json> <table.txt>...
// keys.json is a JSON array of Thai source strings; each table line is "index || en || ja || zh",
// with \n written as a backslash-n. A line whose English is "=" is skipped.
import fs from 'node:fs';
const [dir, keysFile, ...tables] = process.argv.slice(2);
const keys = JSON.parse(fs.readFileSync(keysFile, 'utf8'));
const BACKSLASH = String.fromCharCode(92);
const unescape = (text) => text.split(BACKSLASH + 'r').join('\r').split(BACKSLASH + 'n').join('\n').split(BACKSLASH + '"').join('"');
const locales = ['en', 'ja', 'zh'];
const read = (l) => { const s = fs.readFileSync(`${dir}/${l}.ts`, 'utf8'); return JSON.parse(s.slice(s.indexOf('{'), s.lastIndexOf('}') + 1)); };
const dicts = Object.fromEntries(locales.map((l) => [l, read(l)]));
const marks = (text) => (text.match(/\{\d+\}/g) || []).sort().join();
let applied = 0, skipped = 0;
for (const table of tables) for (const line of fs.readFileSync(table, 'utf8').split(/\r?\n/)) {
  const match = /^(\d+) \|\|(.*)$/.exec(line);
  if (!match) continue;
  const key = keys[Number(match[1])];
  const parts = match[2].split('||').map((part) => unescape(part.trim()));
  if (parts.length !== 3 || parts[0] === '=' || !(key in dicts.en)) { skipped++; continue; }
  const lead = key.match(/^\s*/)[0], tail = key.match(/\s*$/)[0];
  locales.forEach((locale, index) => {
    if (marks(parts[index]) !== marks(key)) { console.error('placeholder mismatch', match[1], locale); return; }
    dicts[locale][key] = lead + parts[index].trim() + tail;
  });
  applied++;
}
for (const l of locales) fs.writeFileSync(`${dir}/${l}.ts`, `// Generated by scripts/i18n-merge.mjs. Keep translations keyed by Thai source text.\nconst text: Record<string, string> = ${JSON.stringify(dicts[l], null, 2)};\nexport default text;\n`);
console.log({ applied, skipped });
